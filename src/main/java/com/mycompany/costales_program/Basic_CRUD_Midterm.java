    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
        // TODO add your handling code here:
        int selectedRow = tblStudents.getSelectedRow();
        
        if(selectedRow == -1) {
            JOptionPane.showMessageDialog(this, "Please select a row first.");
            return;
        }
            
        tblStudents.setValueAt(txtStudentID.getText(), selectedRow, 0);
        tblStudents.setValueAt(txtName.getText(), selectedRow, 1);
        tblStudents.setValueAt(txtAge.getText(), selectedRow, 2);
        tblStudents.setValueAt(txtCourse.getText(), selectedRow, 3);
        
        JOptionPane.showMessageDialog(this, "Student is UPDATED succesfully.");
    }//GEN-LAST:event_btnUpdateActionPerformed

    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
        // TODO add your handling code here:
        int selectedRow = tblStudents.getSelectedRow();
        
        if(selectedRow == -1) {
            JOptionPane.showMessageDialog(this, "Please select a row first.");
            return;
        }
        
        int confirm = JOptionPane.showConfirmDialog(this,
                "Are you sure you want to delete this Student?",
                "Confirm Delete",
                JOptionPane.YES_NO_OPTION
        );
        
        if (confirm == JOptionPane.YES_OPTION) {
            DefaultTableModel model = (DefaultTableModel) tblStudents.getModel();
            model.removeRow(selectedRow);
        }
        
        txtStudentID.setText("");
        txtName.setText("");
        txtAge.setText("");
        txtCourse.setText("");
        
        JOptionPane.showMessageDialog(this, "Student is DELETED succesfully.");
    }//GEN-LAST:event_btnDeleteActionPerformed

