    private void tblStudentsMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblStudentsMouseClicked
        // TODO add your handling code here:
        
        int selectedRow = tblStudents.getSelectedRow();
        
        txtStudentID.setText(tblStudents.getValueAt(selectedRow, 0).toString());
        txtName.setText(tblStudents.getValueAt(selectedRow, 1).toString());
        txtAge.setText(tblStudents.getValueAt(selectedRow, 2).toString());
        txtCourse.setText(tblStudents.getValueAt(selectedRow, 3).toString());
    }//GEN-LAST:event_tblStudentsMouseClicked

    private void btnAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddActionPerformed
        // TODO add your handling code here:
        
        String studentID = txtStudentID.getText();
        String name = txtName.getText();
        String age = txtAge.getText();
        String course = txtCourse.getText();
        
        DefaultTableModel model = (DefaultTableModel) tblStudents.getModel();
        
        model.addRow(new Object[]{
            studentID,
            name,
            age,
            course
        });
    }//GEN-LAST:event_btnAddActionPerformed

